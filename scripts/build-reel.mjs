#!/usr/bin/env node

/**
 * Turns content/reel.json into js/reel-config.js.
 *
 * The reel is injected by an inline script in index.html and has to be on
 * screen immediately, so it cannot wait on a fetch for its own copy. The config
 * ships as a tiny script instead, loaded in front of js/intro.js, which merges
 * it over the literals it already holds. A missing or malformed config
 * therefore costs nothing: the reel plays exactly as it is written.
 *
 *   node scripts/build-reel.mjs            write js/reel-config.js
 *   node scripts/build-reel.mjs --check    fail if it is out of date
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { checkReel } from '../js/lib/schema.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'content/reel.json');
const TARGET = path.join(ROOT, 'js/reel-config.js');
const CHECK = process.argv.includes('--check');

const HEADER = '/* Generated by scripts/build-reel.mjs from content/reel.json. Do not edit. */\n';

const reel = JSON.parse(await readFile(SOURCE, 'utf8'));

const problems = checkReel(reel);
if (problems.length) {
  console.error(`content/reel.json has ${problems.length} problem${problems.length === 1 ? '' : 's'}:`);
  for (const problem of problems) console.error(`- ${problem.key}: ${problem.message}`);
  process.exit(1);
}

const output = `${HEADER}window.__REEL = ${JSON.stringify(reel)};\n`;
const existing = await readFile(TARGET, 'utf8').catch(() => '');

if (existing === output) {
  console.log('Reel config is up to date.');
} else if (CHECK) {
  console.error('js/reel-config.js is out of date; run npm run build.');
  process.exit(1);
} else {
  await writeFile(TARGET, output, 'utf8');
  console.log(`Wrote js/reel-config.js (${output.length} bytes).`);
}
