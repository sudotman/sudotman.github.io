"""Renders the reel's soundtrack as stems, and the single-file fallback.

    python3 scripts/soundtrack/render.py        (npm run soundtrack; needs numpy and ffmpeg)

audio.py is run once per voice. Drums, bass and effects come out identical every time and are
kept once; the chords stem is kept per voice. js/intro.js plays one chords stem with the three
shared ones, each through its own fader, then soft-clips the sum exactly as audio.py's master
did: tanh(0.85 x), normalised. That curve is written to sounds/reel/stems.json as two numbers,
and npm run build carries the manifest into js/reel-config.js.

Stems are stored scaled down by `headroom`, so that with every fader at its top (1.5) the sum
still fits the WaveShaper's [-1, 1] input; `drive` folds that scale back into the curve.

sounds/intro.mp3 is the default mix (synth voice, every fader at 1), played when the manifest or
a stem is missing.
"""
import hashlib, json, os, subprocess, sys, tempfile
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'sounds', 'reel')
VOICES = ['synth', 'rhodes', 'mallets', 'sitar', 'strings']   # keep in step with REEL_VOICES in js/lib/schema.js
SHARED = ['drums', 'bass', 'effects']
MONO = {'drums', 'bass'}                                      # centred to within 35 dB; stored mono, half the bytes
SR, TOP = 48000, 1.5                                          # TOP: the highest a fader goes
LOUDNESS, CEILING = -15.0, -0.5                               # web-audio.sh's loudnorm target; a sample-peak cap

def ffmpeg(*args, data=None):
    return subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', *args], input=data, capture_output=True, check=True)

def encode(signal, path, *quality, channels=2):
    pcm = np.ascontiguousarray(signal.T.astype('<f4')).tobytes()
    ffmpeg('-f', 'f32le', '-ar', str(SR), '-ac', '2', '-i', '-', '-ac', str(channels), '-c:a', 'libmp3lame', *quality, '-ar', str(SR), path, data=pcm)

def measure(signal):
    """Integrated loudness and true peak of a stereo signal, from ffmpeg's loudnorm analysis."""
    pcm = np.ascontiguousarray(signal.T.astype('<f4')).tobytes()
    run = subprocess.run(['ffmpeg', '-hide_banner', '-f', 'f32le', '-ar', str(SR), '-ac', '2', '-i', '-',
                          '-af', f'loudnorm=I={LOUDNESS}:LRA=11:print_format=json', '-f', 'null', '-'],
                         input=pcm, capture_output=True, check=True)
    text = run.stderr.decode()
    report = json.loads(text[text.rindex('{'):text.rindex('}') + 1])
    return float(report['input_i'])

with tempfile.TemporaryDirectory() as tmp:
    jobs = [subprocess.Popen([sys.executable, os.path.join(HERE, 'audio.py'), 'web'], cwd=tmp, stdout=subprocess.DEVNULL,
                             env={**os.environ, 'VOICE': voice, 'STEMS_OUT': os.path.join(tmp, voice)}) for voice in VOICES]
    if any(job.wait() for job in jobs): sys.exit('audio.py failed')
    load = lambda voice, name: np.load(os.path.join(tmp, voice, name + '.npy')).astype(np.float64)
    shared = {name: load('synth', name) for name in SHARED}
    chords = {voice: load(voice, 'chords') for voice in VOICES}
    for voice in VOICES[1:]:
        for name in SHARED:
            if not np.array_equal(load(voice, name).astype(np.float32), shared[name].astype(np.float32)):
                sys.exit(f'{name} differs under the {voice} voice; the shared stems must not depend on it')

# The master, as audio.py made it: soft clip, normalise to 0.89, then a fixed gain to the loudness
# the old loudnorm pass aimed for. loudnorm also limited; a fixed gain cannot, so it is capped at
# a sample peak instead. Web Audio mixes in floating point, so that is the ceiling that matters.
mix = sum(shared.values()) + chords['synth']
clipped = np.tanh(mix * 0.85)
normalise = 0.89 / np.max(np.abs(clipped))
loudness = measure(clipped * normalise)
gain = 10 ** (min(LOUDNESS - loudness, CEILING - 20 * np.log10(0.89)) / 20)
headroom = TOP * (sum(np.max(np.abs(s)) for s in shared.values()) + max(np.max(np.abs(s)) for s in chords.values()))

os.makedirs(OUT, exist_ok=True)
files = {name: shared[name] for name in SHARED} | {f'chords-{voice}': chords[voice] for voice in VOICES}
digest = hashlib.sha256()
for name, signal in files.items():
    path = os.path.join(OUT, name + '.mp3')
    encode(signal / headroom, path, '-q:a', '7', channels=1 if name in MONO else 2)
    digest.update(open(path, 'rb').read())
    print(f'{name:16} {os.path.getsize(path) / 1024:6.1f} KB')

fallback = os.path.join(ROOT, 'sounds', 'intro.mp3')
encode(clipped * normalise * gain, fallback, '-b:a', '128k')
print(f'{"intro.mp3":16} {os.path.getsize(fallback) / 1024:6.1f} KB  (fallback, default mix)')

manifest = {
    'note': 'Generated by scripts/soundtrack/render.py. Do not edit.',
    'version': digest.hexdigest()[:10],
    'voices': VOICES,
    'shared': SHARED,
    'drive': round(0.85 * headroom, 6),
    'makeup': round(normalise * gain, 6),
}
with open(os.path.join(OUT, 'stems.json'), 'w') as f:
    f.write(json.dumps(manifest, indent=2) + '\n')
print(f'loudness {loudness:.1f} LUFS, gain {20 * np.log10(gain):+.1f} dB, headroom {headroom:.3f}')
print('wrote sounds/reel/stems.json; run npm run build to carry it into js/reel-config.js')
