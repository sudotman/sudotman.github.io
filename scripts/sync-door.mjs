#!/usr/bin/env node

/**
 * Copies the words visitors have left at the door into content/door.json.
 *
 * The door (scripts/door/) is the one part of the site that is not a file, and
 * a service can go away. This keeps what it holds in the repository: the front
 * door reads this snapshot first, so the sentence is there even when the door
 * does not answer, and a scheduled workflow commits it so nothing depends on
 * the service for its only copy.
 *
 * Only the words are copied. note from the previous visitor under the door is one at a time on
 * purpose; an archive of every note would undo that.
 *
 * The address comes from content/home.json (door.endpoint). With none set, or
 * with the door not answering, the snapshot is left exactly as it is: a failed
 * sync must never fail a deploy or blank the page.
 *
 *   node scripts/sync-door.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HOME = path.join(ROOT, 'content/home.json');
const TARGET = path.join(ROOT, 'content/door.json');
const NOTE = 'Generated by scripts/sync-door.mjs. Do not edit.';

const home = JSON.parse(await readFile(HOME, 'utf8'));
const endpoint = String(home.door?.endpoint || '').replace(/\/+$/, '');

if (!endpoint) {
  console.log('No door is configured (content/home.json door.endpoint); nothing to sync.');
  process.exit(0);
}

const existing = JSON.parse(await readFile(TARGET, 'utf8').catch(() => 'null'));

async function allWords() {
  const words = [];
  let after = 0;
  for (let page = 0; page < 200; page += 1) {
    const response = await fetch(`${endpoint}/words?after=${after}&limit=1000`, { signal: AbortSignal.timeout(15_000) });
    if (!response.ok) throw new Error(`${endpoint}/words returned ${response.status}`);
    const batch = (await response.json()).words;
    if (!Array.isArray(batch)) throw new Error('the door did not send a list of words');
    for (const item of batch) {
      if (typeof item?.word === 'string' && Number.isInteger(item.id)) words.push(item.word);
    }
    if (batch.length < 1000) return words;
    after = batch.at(-1).id;
  }
  throw new Error('the door has more words than this script will page through');
}

try {
  const words = await allWords();
  if (existing && JSON.stringify(existing.words) === JSON.stringify(words)) {
    console.log(`The door's words are up to date (${words.length}).`);
  } else {
    const output = { note: NOTE, syncedAt: new Date().toISOString(), total: words.length, words };
    await writeFile(TARGET, `${JSON.stringify(output, null, 2)}\n`, 'utf8');
    console.log(`Wrote content/door.json (${words.length} words).`);
  }
} catch (error) {
  console.warn(`The door did not answer; content/door.json is unchanged. ${error.message}`);
}
